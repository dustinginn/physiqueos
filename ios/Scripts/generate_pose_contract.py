#!/usr/bin/env python3
"""Generates Native's Progress Photo pose table from the shared contract.

The Server vocabulary is the single authority for which orientation, contraction,
and pose-variant combinations exist. It publishes them as
contracts/progress-photo-pose-contract.v1.json; this script turns that file into
ios/PhysiqueOS/Contracts/ProgressPhotoPoseContractData.swift so Native's controls
derive from the same table the Server validates. Nothing here is hand-edited.

  python3 ios/Scripts/generate_pose_contract.py          # write
  python3 ios/Scripts/generate_pose_contract.py --check  # fail if the Swift file is stale
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CONTRACT = os.path.join(ROOT, "contracts", "progress-photo-pose-contract.v1.json")
OUTPUT = os.path.join(ROOT, "ios", "PhysiqueOS", "Contracts", "ProgressPhotoPoseContractData.swift")


def swift_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    with open(CONTRACT, encoding="utf-8") as handle:
        contract = json.load(handle)
    rows = []
    for item in contract["combinations"]:
        rows.append(
            "        .init(id: {id}, label: {label}, orientation: {orientation}, contractionState: {contraction}, poseVariant: {variant}),".format(
                id=swift_string(item["id"]),
                label=swift_string(item["label"]),
                orientation=swift_string(item["orientation"]),
                contraction=swift_string(item["contractionState"]),
                variant=swift_string(item["poseVariant"]),
            )
        )
    return "\n".join(
        [
            "// GENERATED by ios/Scripts/generate_pose_contract.py from",
            "// contracts/progress-photo-pose-contract.v1.json. Do not edit by hand:",
            "// the Server vocabulary owns this table and a test fails if this file drifts.",
            "",
            "/// The Server's canonical Progress Photo pose combinations, verbatim.",
            "/// `ProgressPhotoPoseContract` derives every Native control and gate from it.",
            "enum ProgressPhotoPoseContractData {",
            "    static let version = " + swift_string(contract["version"]),
            "",
            "    struct Combination: Equatable, Sendable {",
            "        let id: String",
            "        let label: String",
            "        let orientation: String",
            "        let contractionState: String",
            "        let poseVariant: String",
            "    }",
            "",
            "    static let combinations: [Combination] = [",
            *rows,
            "    ]",
            "}",
            "",
        ]
    )


if __name__ == "__main__":
    rendered = render()
    if "--check" in sys.argv:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else None
        if current != rendered:
            sys.stderr.write("ProgressPhotoPoseContractData.swift is out of date; run generate_pose_contract.py.\n")
            sys.exit(1)
        print("ProgressPhotoPoseContractData.swift is current.")
    else:
        with open(OUTPUT, "w", encoding="utf-8") as handle:
            handle.write(rendered)
        print("wrote", OUTPUT)
