import Foundation

/// Read seam for Recovery / Sleep Evidence. Every screen reads exactly one
/// bounded resource: landing (`recovery-sleep`), a ranged trend
/// (`recovery-sleep-trends`), a page of nights (`recovery-sleep-nights`), or
/// one night (`recovery-sleep-night`). Native never loads all history.
protocol RecoverySleepAPI: Sendable {
    func fetchLanding(policy: RecoverySleepReadPolicy) async throws -> RecoverySleepLanding
    func fetchTrends(range: RecoverySleepTrendRange) async throws -> RecoverySleepTrends
    func fetchNights(cursor: String?, limit: Int) async throws -> RecoverySleepNightsPage
    func fetchNight(sleepDay: String) async throws -> RecoverySleepNightDetail
}

enum RecoverySleepReadPolicy: Sendable {
    case cacheFirst, reload
}

enum RecoverySleepAPIError: Error, Equatable {
    /// The Server does not serve Sleep Evidence (yet). Shown as a calm
    /// "not available" state, never as an error.
    case notAvailable
    /// No night exists for the requested sleep day.
    case nightNotFound
}

enum RecoverySleepQuery {
    static let nightsPageLimit = 30
    static let maximumNightsPageLimit = 60

    static func isSleepDayKey(_ value: String) -> Bool {
        value.range(of: #"^\d{4}-\d{2}-\d{2}$"#, options: .regularExpression) != nil
    }
}

// MARK: - Founder Production (Server read models only; never fixtures)

struct ProductionRecoverySleepAPI: RecoverySleepAPI {
    let api: ProductionNativeAPI

    func fetchLanding(policy: RecoverySleepReadPolicy) async throws -> RecoverySleepLanding {
        try await read(RecoverySleepResource.landing, query: [:], policy: policy == .reload ? .reload : .cacheFirst, as: RecoverySleepLanding.self)
    }

    func fetchTrends(range: RecoverySleepTrendRange) async throws -> RecoverySleepTrends {
        try await read(RecoverySleepResource.trends, query: ["range": range.rawValue], policy: .cacheFirst, as: RecoverySleepTrends.self)
    }

    func fetchNights(cursor: String?, limit: Int) async throws -> RecoverySleepNightsPage {
        var query = ["limit": String(min(max(1, limit), RecoverySleepQuery.maximumNightsPageLimit))]
        if let cursor { query["cursor"] = cursor }
        return try await read(RecoverySleepResource.nights, query: query, policy: .cacheFirst, as: RecoverySleepNightsPage.self)
    }

    /// A night is "day truth" (late samples, recomputation): always live.
    func fetchNight(sleepDay: String) async throws -> RecoverySleepNightDetail {
        guard RecoverySleepQuery.isSleepDayKey(sleepDay) else { throw RecoverySleepAPIError.nightNotFound }
        do {
            return try await api.readResource(RecoverySleepResource.night, query: ["sleepDay": sleepDay], policy: .reload, as: RecoverySleepNightDetail.self).data
        } catch ProductionNativeError.notFound(let problem) where problem?.code == "SLEEP_NIGHT_NOT_FOUND" {
            throw RecoverySleepAPIError.nightNotFound
        } catch ProductionNativeError.notFound {
            throw RecoverySleepAPIError.notAvailable
        }
    }

    private func read<Payload: Decodable & Sendable>(
        _ resource: String, query: [String: String], policy: ProductionNativeAPI.ReadPolicy, as type: Payload.Type
    ) async throws -> Payload {
        do {
            return try await api.readResource(resource, query: query, policy: policy, as: type).data
        } catch ProductionNativeError.notFound {
            // An authority that predates the Sleep read model has no route.
            throw RecoverySleepAPIError.notAvailable
        }
    }
}

// MARK: - Sandbox (bundled synthetic fixture; never reachable from Production)

/// Decodes `RecoverySleepFixture.json` — a checked-in example of the exact
/// contract payloads, generated by `ios/Scripts/generate_recovery_sleep_fixture.py`
/// from synthetic values only — through the same decoder configuration
/// `ProductionNativeAPI.readResource` uses.
struct FixtureRecoverySleepAPI: RecoverySleepAPI {
    enum FixtureError: Error { case resourceNotFound }

    struct FixtureFile: Decodable, Sendable {
        let landing: RecoverySleepLanding
        let trends: [String: RecoverySleepTrends]
        let nights: [RecoverySleepNightDetail]
    }

    private let bundle: Bundle

    init(bundle: Bundle = .main) {
        self.bundle = bundle
    }

    func loadFixture() throws -> FixtureFile {
        guard let url = bundle.url(forResource: "RecoverySleepFixture", withExtension: "json") else {
            throw FixtureError.resourceNotFound
        }
        return try RecoverySleepDecoding.decoder().decode(FixtureFile.self, from: Data(contentsOf: url))
    }

    func fetchLanding(policy: RecoverySleepReadPolicy) async throws -> RecoverySleepLanding {
        try loadFixture().landing
    }

    func fetchTrends(range: RecoverySleepTrendRange) async throws -> RecoverySleepTrends {
        let fixture = try loadFixture()
        // Ranges beyond the fixture's history return the longest it has,
        // mirroring a Server with fewer nights than the requested range.
        if let trends = fixture.trends[range.rawValue] ?? fixture.trends[RecoverySleepTrendRange.all.rawValue] {
            return trends
        }
        throw FixtureError.resourceNotFound
    }

    func fetchNights(cursor: String?, limit: Int) async throws -> RecoverySleepNightsPage {
        let all = try loadFixture().nights.map(\.night)
        let start = cursor.flatMap(Int.init) ?? 0
        let end = min(all.count, start + max(1, min(limit, RecoverySleepQuery.maximumNightsPageLimit)))
        guard start < end else { return RecoverySleepNightsPage(items: [], nextCursor: nil) }
        return RecoverySleepNightsPage(items: Array(all[start..<end]), nextCursor: end < all.count ? String(end) : nil)
    }

    func fetchNight(sleepDay: String) async throws -> RecoverySleepNightDetail {
        guard let night = try loadFixture().nights.first(where: { $0.night.sleepDay == sleepDay }) else {
            throw RecoverySleepAPIError.nightNotFound
        }
        return night
    }
}
